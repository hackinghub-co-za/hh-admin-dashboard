-- Hacking Hub Admin Dashboard - Member Persistence Migration
-- Run this in the Supabase SQL Editor (after schema.sql has already been applied).
--
-- Part 1 fixes a live bug: every "admin full write access" policy in schema.sql
-- checks admin status via a subquery on public.profiles from *within a policy on
-- profiles itself*, which Postgres rejects with "infinite recursion detected in
-- policy for relation profiles" (42P17). This means no admin write has ever
-- actually succeeded against this project. The fix is a SECURITY DEFINER helper
-- function, which runs with elevated privileges and bypasses RLS internally,
-- breaking the recursion cycle.
--
-- Part 2 adds tables for data that doesn't fit the existing auth.users-keyed
-- schema: real members here are PayFast payers identified by email, not people who
-- have signed into this app via Google OAuth, so these are keyed by email instead
-- of a foreign key to auth.users.

-- =========================================================================
-- PART 1: FIX THE RLS RECURSION BUG
-- =========================================================================

CREATE OR REPLACE FUNCTION public.is_admin(uid UUID)
RETURNS BOOLEAN
LANGUAGE sql
SECURITY DEFINER
SET search_path = public
STABLE
AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.profiles WHERE profiles.id = uid AND profiles.role = 'admin'
  );
$$;

DROP POLICY IF EXISTS "Allow admins full write access to profiles" ON public.profiles;
CREATE POLICY "Allow admins full write access to profiles" ON public.profiles
    FOR ALL USING (public.is_admin(auth.uid()));

DROP POLICY IF EXISTS "Allow admins full write access to meetups" ON public.meetups;
CREATE POLICY "Allow admins full write access to meetups" ON public.meetups
    FOR ALL USING (public.is_admin(auth.uid()));

