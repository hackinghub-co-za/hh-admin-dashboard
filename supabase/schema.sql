-- Payments Policies
CREATE POLICY "Allow members to view their own payment ledger" ON public.payments
    FOR SELECT USING (auth.uid() = member_id);

CREATE POLICY "Allow admins full write access to payments" ON public.payments
    FOR ALL USING (
        EXISTS (
            SELECT 1 FROM public.profiles
            WHERE public.profiles.id = auth.uid() AND public.profiles.role = 'admin'
        )
    );


-- =========================================================================
-- AUTOMATED PROFILE CREATION TRIGGER
-- =========================================================================

-- Create trigger function to create profile entry when a user signs up/logs in via Google OAuth
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
BEGIN
    INSERT INTO public.profiles (id, email, full_name, avatar_url, role)
    VALUES (
        new.id,
        new.email,
        new.raw_user_meta_data->>'full_name',
        new.raw_user_meta_data->>'avatar_url',
        CASE 
            WHEN new.email LIKE '%@hackinghub.co.za' THEN 'admin'
            ELSE 'member'
        END
    );
    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Trigger execution bind
CREATE OR REPLACE TRIGGER on_auth_user_created
    AFTER INSERT ON auth.users
    FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();
